// CodeMind Academy — Session materials / PDF delivery (Phase 14).
//
// THE CONTRACT
// ===========
// Session PDFs are stored ONCE as a `MediaAsset(DOCUMENT, LOCAL_PRIVATE)` and
// referenced by a `Material(ADMIN_UPLOADED)` row hanging off a Lesson. There is
// no second PDF table, no public filesystem path, and no new `pdfUrl` writes.
//
//   Lesson
//     └── Material(lessonId, kind=ADMIN_UPLOADED, trackScope, isActive, mediaAssetId)
//           └── MediaAsset(kind=DOCUMENT, storage=LOCAL_PRIVATE, storageKey, isPrivate)
//                 └── bytes under MEDIA_ROOT (never under /public)
//
// THE RULES THIS MODULE OWNS
// ==========================
//  1. Upload validation is `validatePdfUpload` in `src/lib/media.ts` — MIME,
//     extension, magic bytes (`%PDF-`), size cap. Callers MUST pass real bytes.
//  2. Storage keys are generated by `makeStorageKey` — never taken from the
//     client. Path traversal in a stored key is rejected by `resolveSafePath`.
//  3. Track isolation uses the SAME predicates as Phase 12
//     (`canAccessTrackScope` / `eligibleTrackScopes`). A LANGUAGE student never
//     downloads ARABIC material; SHARED is available to both. The decision is
//     derived from the student's own `schoolType` row (or a parent's linked
//     children's tracks) — never from UI locale, never from a request param.
//  4. Authorization for download reuses `canAccessLesson` (enrollment + course
//     + track + lifecycle + progression). Parent access reuses
//     `isParentLessonPreviewAllowed` (child course + child track + PUBLISHED +
//     not archived). There is no second progression engine here.
//  5. Uniqueness of "one active PDF per lesson × trackScope" is enforced by
//     deactivating prior active rows of the same scope on replace, not by a
//     partial unique index (deactivated history must survive for refcounting).
//  6. MediaAsset bytes are deleted ONLY when no Material (and no SessionVideo /
//     QuizAttemptEvidence) still references them. Reference counting is the
//     same pattern session-video DELETE already uses.
//  7. Student/parent payloads expose SAFE DESCRIPTORS only
//     (`id`, `title`, `kind`, `trackScope`, `downloadUrl`, `mimeType`,
//     `sizeBytes`). Never `storageKey`, never a filesystem path, never a
//     private URL. Locked/unpublished/wrong-track lessons do not reveal
//     material ids.
//  8. Legacy `Lesson.pdfUrl` is READ-ONLY compatibility. New uploads never
//     write it. Existing non-placeholder values may still be surfaced as a
//     legacy descriptor so older content keeps working until sunset.
//
// See docs/PHASE_14_PDF_SESSION_MATERIALS.md for the full contract.

