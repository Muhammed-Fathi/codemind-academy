const PLACEHOLDER_MARKERS = new Set(["", "#", "##", "./#", "null", "none", "-"]);

/** A legacy string url counts only when it is actually a url-ish value. */
export function isUsableLegacyPdfUrl(value: string | null | undefined): boolean {
  if (typeof value !== "string") return false;
  const v = value.trim();
  return v.length > 0 && !PLACEHOLDER_MARKERS.has(v.toLowerCase());
}

/**
 * Build the safe student-facing material list for a lesson.
 *
 * `materials` are already-loaded active Material rows (with optional media).
 * `legacyPdfUrl` is the lesson's `pdfUrl` column — surfaced only as a
 * LEGACY_URL descriptor when no Material of the matching scope is present and
 * the url is usable. Locked callers MUST pass `includeProtected: false` so
 * material ids are never leaked for sessions the student cannot open.
 */
export function buildMaterialDescriptors(input: {
  materials?: readonly {
    id: string;
    title?: string | null;
    kind?: string | null;
    trackScope?: unknown;
    isActive?: boolean | null;
    mediaAssetId?: string | null;
    media?: {
      mimeType?: string | null;
      sizeBytes?: number | null;
    } | null;
  }[] | null;
  legacyPdfUrl?: string | null;
  /** When false, returns an empty list (locked / unpublished redaction). */
  includeProtected?: boolean;
  /** Optional filter: only scopes the viewer is eligible for. */
  eligibleScopes?: Iterable<TrackScope> | null;
}): MaterialDescriptor[] {
  if (input.includeProtected === false) return [];

  const eligible = input.eligibleScopes
    ? new Set(input.eligibleScopes)
    : null;

  const out: MaterialDescriptor[] = [];
  const materials = Array.isArray(input.materials) ? input.materials : [];
  for (const m of materials) {
    if (m?.isActive === false) continue;
    if (!m?.id) continue;
    const scope = normalizeTrackScope(m.trackScope) ?? "SHARED";
    if (eligible && !eligible.has(scope)) continue;
    // A material without a media asset is not downloadable; skip rather than
    // invent a broken descriptor.
    if (!m.mediaAssetId && m.kind !== "GENERATED") {
      // Still surface ADMIN_UPLOADED only when an asset is linked.
      if (m.kind === "ADMIN_UPLOADED" || !m.kind) continue;
    }
    const kind: MaterialDescriptor["kind"] =
      m.kind === "GENERATED" ? "GENERATED" : "ADMIN_UPLOADED";
    out.push({
      id: m.id,
      title: (m.title && String(m.title).trim()) || "Session PDF",
      kind,
      trackScope: scope,
      downloadUrl: m.mediaAssetId ? `/api/materials/${m.id}` : null,
      mimeType: m.media?.mimeType ?? (m.mediaAssetId ? "application/pdf" : null),
      sizeBytes:
        typeof m.media?.sizeBytes === "number" ? m.media.sizeBytes : null,
      legacy: false,
    });
  }

  // Legacy compatibility: only when no Material descriptor exists at all for
  // this payload, and only when the url is a real non-placeholder value.
  // Never invent a material id for a legacy url — the client uses the raw
  // external url, which is the documented compatibility path.
  if (out.length === 0 && isUsableLegacyPdfUrl(input.legacyPdfUrl)) {
    out.push({
      id: "legacy-pdf",
      title: "Session PDF",
      kind: "LEGACY_URL",
      trackScope: "SHARED",
      downloadUrl: String(input.legacyPdfUrl).trim(),
      mimeType: "application/pdf",
      sizeBytes: null,
      legacy: true,
    });
  }

  return out;
}

