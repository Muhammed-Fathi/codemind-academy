/**
 * Authorize a download of material `materialId` for the given viewer.
 *
 * Checks (fail closed, in order):
 *   1. authenticated (caller supplies user)
 *   2. role is STUDENT | PARENT | TEACHER | ADMIN
 *   3–8. for STUDENT: canAccessLesson (enrollment, course, track, lifecycle,
 *        progression) + material trackScope eligibility
 *   3–8. for PARENT: isParentLessonPreviewAllowed (child course + child track
 *        + PUBLISHED + not archived) + material trackScope in parent scopes
 *   3–8. for TEACHER/ADMIN: material exists + asset private — staff may review
 *   9. material belongs to its lesson and is active
 *  10. asset exists, isPrivate, and is MANAGED PRIVATE storage
 *      (LOCAL_PRIVATE or S3) with a storageKey — the backend that holds the
 *      bytes never changes who may read them
 */
export async function authorizeMaterialDownload(params: {
  materialId: string;
  user: { id: string; role: string } | null | undefined;
  client?: typeof db;
}): Promise<MaterialAccess> {
  const client = params.client ?? db;
  const user = params.user;
  if (!user) return { allowed: false, reason: "UNAUTHORIZED" };

  const material = await client.material.findUnique({
    where: { id: params.materialId },
    select: {
      id: true,
      lessonId: true,
      title: true,
      trackScope: true,
      isActive: true,
      mediaAssetId: true,
      kind: true,
      lesson: {
        select: {
          id: true,
          status: true,
          trackScope: true,
          curriculumStatus: true,
          unitId: true,
          topicId: true,
          unit: {
            select: { part: { select: { courseId: true } } },
          },
          topic: {
            select: {
              unit: { select: { part: { select: { courseId: true } } } },
            },
          },
        },
      },
      media: {
        select: {
          id: true,
          storageKey: true,
          mimeType: true,
          sizeBytes: true,
          originalName: true,
          isPrivate: true,
          storage: true,
          kind: true,
        },
      },
    },
  });

  if (!material) return { allowed: false, reason: "MATERIAL_NOT_FOUND" };
  if (!material.isActive) return { allowed: false, reason: "MATERIAL_INACTIVE" };
  if (!material.mediaAssetId || !material.media) {
    return { allowed: false, reason: "ASSET_NOT_FOUND" };
  }
  const asset = material.media;
  if (
    // Check #10 — the asset must be a MANAGED PRIVATE object this server holds
    // the bytes for: LOCAL_PRIVATE (the private volume) OR S3 (the R2 bucket).
    // Accepting S3 widens WHICH private backend may satisfy the check; it does
    // NOT widen WHO may read. Everything before this line (auth, role, the
    // lesson gate, track scope, lifecycle, active material) is unchanged, and
    // the verdict below is still "authorized → server proxies bytes from the
    // backend". No signed URL, no redirect, no external fetch is ever produced
    // from this gate, and a non-managed value (EXTERNAL_URL / empty / unknown)
    // is refused with the same non-oracle reason as a missing asset.
    !isManagedPrivateStorage(asset.storage) ||
    !asset.storageKey ||
    // Documents must be private; never serve a non-private document asset
    // through this route (defense in depth against a mis-tagged row).
    asset.isPrivate !== true
  ) {
    return { allowed: false, reason: "ASSET_NOT_FOUND" };
  }

  const lesson = material.lesson;
  if (!lesson) return { allowed: false, reason: "MATERIAL_NOT_FOUND" };
  const courseId =
    lesson.unit?.part.courseId ??
    lesson.topic?.unit.part.courseId ??
    null;
  const materialScope = normalizeTrackScope(material.trackScope) ?? "SHARED";
  const lessonScope = normalizeTrackScope(lesson.trackScope) ?? "SHARED";

  const role = String(user.role || "").toUpperCase();

  if (role === "STUDENT") {
    const student = await client.student.findUnique({
      where: { userId: user.id },
      select: { id: true, schoolType: true },
    });
    if (!student) return { allowed: false, reason: "FORBIDDEN_ROLE" };

    // 3–8: full lesson gate (enrollment, course, lesson track, lifecycle,
    // progression). Wrong-track / unpublished / locked → same non-oracle
    // reasons canAccessLesson already uses.
    const access = await canAccessLesson(student.id, lesson.id);
    if (!access.allowed) {
      return {
        allowed: false,
        reason: access.reason ?? "LESSON_NOT_FOUND",
      };
    }

    // Material-level track (may be narrower than the lesson).
    const schoolType =
      normalizeSchoolType(student.schoolType) ??
      (await getStudentSchoolType(student.id));
    if (!canAccessTrackScope(schoolType, materialScope)) {
      return { allowed: false, reason: "TRACK_DENIED" };
    }
  } else if (role === "PARENT") {
    const allowed = await isParentLessonPreviewAllowed(
      user.id,
      {
        status: lesson.status,
        curriculumStatus: lesson.curriculumStatus,
        trackScope: lesson.trackScope,
      },
      courseId
    );
    if (!allowed) return { allowed: false, reason: "MATERIAL_NOT_FOUND" };

    // Parent track set is the UNION of linked enrolled children's tracks.
    // SHARED is always included by getParentTrackScopes; track-specific
    // material requires the matching child track.
    const scopes = await getParentTrackScopes(user.id);
    if (materialScope !== "SHARED" && !scopes.has(materialScope)) {
      return { allowed: false, reason: "TRACK_DENIED" };
    }
  } else if (role === "ADMIN" || role === "TEACHER") {
    // Staff may review any active material. Lifecycle is not a barrier for
    // staging review — that is the point of DRAFT/READY being admin-visible.
  } else {
    return { allowed: false, reason: "FORBIDDEN_ROLE" };
  }

  // Lifecycle note: for students/parents the lesson gate already required
  // PUBLISHED. Staff skip it. We still refuse ARCHIVED for everyone except
  // when staff is reviewing — staff can see archived too (grading history).
  if (
    role !== "ADMIN" &&
    role !== "TEACHER" &&
    (!isStudentVisibleStatus(lesson.status) ||
      String(lesson.curriculumStatus).toUpperCase() === "ARCHIVED")
  ) {
    return { allowed: false, reason: "MATERIAL_NOT_FOUND" };
  }

  return {
    allowed: true,
    reason: null,
    material: {
      id: material.id,
      lessonId: material.lessonId,
      title: material.title,
      trackScope: materialScope,
      isActive: material.isActive,
      mediaAssetId: material.mediaAssetId,
    },
    asset: {
      id: asset.id,
      storageKey: asset.storageKey!,
      mimeType: asset.mimeType,
      sizeBytes: asset.sizeBytes,
      originalName: asset.originalName,
      isPrivate: asset.isPrivate,
      storage: asset.storage,
      kind: asset.kind,
    },
    lesson: {
      id: lesson.id,
      status: String(lesson.status),
      trackScope: lessonScope,
      curriculumStatus: String(lesson.curriculumStatus),
      courseId,
    },
  };
}

/**
 * HTTP status mapping for a material access denial. Mirrors denyProgression
 * semantics so probing material ids cannot enumerate content:
 *   MATERIAL_NOT_FOUND / ASSET_NOT_FOUND / MATERIAL_INACTIVE / TRACK_DENIED
 *     when the lesson itself would 404 → 404
 *   PREVIOUS_SESSION_INCOMPLETE / NOT_ENROLLED → 403 with code
 *   UNAUTHORIZED → 401
 *   FORBIDDEN_ROLE → 403
 */
export function materialAccessHttpStatus(
  reason: MaterialAccessReason
): 401 | 403 | 404 {
  if (reason === "UNAUTHORIZED") return 401;
  if (
    reason === "NOT_ENROLLED" ||
    reason === "PREVIOUS_SESSION_INCOMPLETE" ||
    reason === "FORBIDDEN_ROLE"
  ) {
    return 403;
  }
  // MATERIAL_NOT_FOUND, ASSET_NOT_FOUND, MATERIAL_INACTIVE, TRACK_DENIED,
  // LESSON_NOT_FOUND — never confirm the id is real.
  return 404;
}

/** Content-Disposition helper. */
export function materialContentDisposition(
  filename: string | null | undefined,
  download: boolean
): string {
  const raw = (filename && String(filename).trim()) || "document.pdf";
  // RFC 5987-ish safe token: strip quotes/newlines; keep ASCII filename.
  const safe = raw
    .replace(/["\r\n\\]/g, "")
    .replace(/[^\x20-\x7E]/g, "_")
    .slice(0, 180) || "document.pdf";
  const type = download ? "attachment" : "inline";
  return `${type}; filename="${safe}"`;
}

