/**
 * Parse a trackScope supplied by an admin on upload.
 *   - absent / empty → null (caller inherits the lesson's scope)
 *   - SHARED/ARABIC/LANGUAGE → that scope
 *   - anything else → reject
 */
export function parseMaterialTrackScopeInput(
  raw: unknown
):
  | { ok: true; specified: false }
  | { ok: true; specified: true; value: TrackScope }
  | { ok: false } {
  if (raw === undefined || raw === null) return { ok: true, specified: false };
  if (typeof raw !== "string") return { ok: false };
  const v = raw.trim();
  if (v === "") return { ok: true, specified: false };
  const scope = normalizeTrackScope(v);
  if (!scope) return { ok: false };
  return { ok: true, specified: true, value: scope };
}

/**
 * DB finalization for an ALREADY-VERIFIED lesson-PDF upload (Phase 23).
 *
 * Creates the Material(ADMIN_UPLOADED) + MediaAsset(DOCUMENT) rows for bytes
 * that are ALREADY in private storage under `storageKey` — either written by
 * `uploadLessonPdfMaterial` (buffered path) or uploaded by the browser
 * directly to R2 and verified by the presigned completion flow. Ordering is
 * the same everywhere: BYTES FIRST → verification → ROWS, so a DB failure can
 * never strand a phantom MediaAsset, and the caller owns deleting the object
 * when finalization throws.
 *
 * Steps (unchanged from the original inline implementation):
 *   1. Resolve the display title.
 *   2. Capture prior active Material rows of the same (lesson × trackScope).
 *   3. In one transaction: deactivate the prior rows, create the MediaAsset
 *      (recording `storage`, the backend that actually holds the bytes) and
 *      the Material row.
 *   4. Reference-count cleanup of orphaned prior assets (after commit).
 *
 * Throws on DB failure; returns the same `ok` shape as
 * `uploadLessonPdfMaterial` on success.
 */
export async function finalizeLessonPdfMaterial(
  input: {
    /** The (already validated, non-archived) lesson these rows attach to. */
    lesson: { id: string; title: string | null };
    trackScope: TrackScope;
    title?: string | null;
    /** The `MediaAsset.storage` value describing where the bytes live. */
    storage: ManagedPrivateStorageValue;
    storageKey: string;
    mimeType: string;
    sizeBytes: number;
    originalName: string;
    actorUserId?: string | null;
  },
  client: typeof db = db,
  options?: {
    /**
     * Phase 23 concurrency gate — runs FIRST inside the same transaction
     * that performs the row writes. See `FinalizeLessonPdfSerializeGate`.
     */
    serialize?: (tx: any) => Promise<FinalizeLessonPdfSerializeGate>;
  }
): Promise<FinalizeLessonPdfResult> {
  // The caller-supplied `storageKey` is ALWAYS server-generated — either the
  // buffered path's `makeStorageKey` output or the exact key bound inside the
  // HMAC intent token (Phase 23). Destructured so the row creation below uses
  // it directly, never reading it from a request-shaped object.
  const { storage, storageKey, mimeType, sizeBytes, originalName, trackScope } = input;
  const title =
    (typeof input.title === "string" && input.title.trim()) ||
    input.originalName ||
    `${input.lesson.title} PDF`;

  // Capture prior active materials so we can deactivate + maybe clean up.
  const prior = await client.material.findMany({
    where: {
      lessonId: input.lesson.id,
      trackScope: input.trackScope,
      isActive: true,
      kind: "ADMIN_UPLOADED",
    },
    select: { id: true, mediaAssetId: true },
  });

  const apply = async (
    tx: any
  ): Promise<
    | {
        created: {
          asset: { id: string };
          material: { id: string; title: string };
        };
      }
    | { gate: FinalizeLessonPdfResult }
  > => {
    // Phase 23 — concurrency gate: under the per-storage-key database lock,
    // re-check whether the presigned upload was already finalized by a twin
    // completion. `proceed: false` short-circuits the ENTIRE finalize (no
    // deactivate, no rows, no refcount cleanup) and returns the twin's own
    // outcome — the sequential-replay idempotency guarantee, now held under
    // concurrency as well.
    if (options?.serialize) {
      const gate = await options.serialize(tx);
      if (!gate.proceed) return { gate: gate.outcome };
    }
    if (prior.length > 0) {
      await tx.material.updateMany({
        where: { id: { in: prior.map((p) => p.id) } },
        data: { isActive: false },
      });
    }

    const asset = await tx.mediaAsset.create({
      data: {
        kind: "DOCUMENT",
        // The backend that ACTUALLY holds these bytes (LOCAL_PRIVATE | S3) —
        // resolved by the caller from the active selector or, for the
        // presigned flow, the backend that received the direct upload.
        storage,
        storageKey,
        mimeType,
        sizeBytes,
        originalName,
        isPrivate: true,
        createdById: input.actorUserId ?? null,
      },
    });

    const material = await tx.material.create({
      data: {
        lessonId: input.lesson.id,
        kind: "ADMIN_UPLOADED",
        title: title.slice(0, 200),
        mediaAssetId: asset.id,
        // storageKey on Material is legacy; the asset owns the key. Leave null
        // so nothing ever confuses the two.
        storageKey: null,
        trackScope,
        isActive: true,
      },
    });

    return { created: { asset, material } };
  };

  let created: Awaited<ReturnType<typeof apply>>;
  if (typeof (client as { $transaction?: unknown }).$transaction === "function") {
    created = await (client as typeof db).$transaction(apply);
  } else {
    created = await apply(client);
  }
  // A twin completion won the race: the gate already produced the final
  // outcome (idempotent replay / fail-closed) — nothing was written, so the
  // refcount cleanup below must NOT run.
  if ("gate" in created) return created.gate;
  const { asset: createdAsset } = created.created;

  // Reference-counted cleanup: detach deactivated materials from their prior
  // assets, then delete any asset that nothing else still references. An asset
  // still pointed at by another active Material (or a SessionVideo / evidence
  // row) is retained — never delete shared bytes.
  const cleanedUpAssets = await releaseDetachedAssets(
    prior
      .map((p) => p.mediaAssetId)
      .filter((id): id is string => !!id && id !== createdAsset.id),
    client
  );

  return {
    ok: true,
    material: {
      id: created.created.material.id,
      lessonId: input.lesson.id,
      title: created.created.material.title,
      kind: "ADMIN_UPLOADED",
      trackScope: input.trackScope,
      isActive: true,
      mediaAssetId: createdAsset.id,
      downloadUrl: `/api/materials/${created.created.material.id}`,
      mimeType,
      sizeBytes,
      originalName,
    },
    replaced: prior.map((p) => ({
      materialId: p.id,
      mediaAssetId: p.mediaAssetId,
    })),
    cleanedUpAssets,
  };
}

/**
 * Upload (or replace) the active PDF material for a lesson × trackScope.
 *
 * Side effects, in order, inside a transaction where possible:
 *   1. Validate bytes (MIME / extension / magic / size).
 *   2. Write private file under an unguessable key, into the ACTIVE backend.
 *   3. Finalize rows via `finalizeLessonPdfMaterial`: deactivate prior active
 *      Material rows of the same (lesson, trackScope), create
 *      MediaAsset(DOCUMENT, storage=active backend, isPrivate) + the new
 *      Material(ADMIN_UPLOADED) row, then reference-count cleanup of orphaned
 *      prior assets (after commit).
 *
 * NEVER writes `Lesson.pdfUrl`. NEVER trusts a client-supplied storageKey.
 */
export async function uploadLessonPdfMaterial(
  input: MaterialUploadInput,
  client: typeof db = db
): Promise<MaterialUploadResult> {
  const lesson = await client.lesson.findUnique({
    where: { id: input.lessonId },
    select: {
      id: true,
      title: true,
      titleAr: true,
      trackScope: true,
      curriculumStatus: true,
      status: true,
    },
  });
  if (!lesson) {
    return {
      ok: false,
      code: "LESSON_NOT_FOUND",
      message: "Lesson not found",
    };
  }
  if (String(lesson.curriculumStatus).toUpperCase() === "ARCHIVED") {
    return {
      ok: false,
      code: "LESSON_ARCHIVED",
      message: "Cannot attach materials to an archived lesson",
    };
  }

  const scopeParse = parseMaterialTrackScopeInput(input.trackScope);
  if (!scopeParse.ok) {
    return {
      ok: false,
      code: "INVALID_TRACK_SCOPE",
      message: "trackScope must be SHARED, ARABIC, or LANGUAGE",
    };
  }
  const trackScope: TrackScope = scopeParse.specified
    ? scopeParse.value
    : normalizeTrackScope(lesson.trackScope) ?? "SHARED";

  const validation = validatePdfUpload({
    buffer: input.buffer,
    claimedMime: input.claimedMime,
    originalName: input.originalName,
    maxBytes: input.maxBytes ?? MAX_PDF_BYTES,
  });
  if (!validation.ok) {
    return {
      ok: false,
      code: "VALIDATION_FAILED",
      message: validation.message,
      validation,
    };
  }

  const storageKey = makeStorageKey("session-pdfs", "pdf");
  const buffer = Buffer.isBuffer(input.buffer)
    ? input.buffer
    : Buffer.from(input.buffer);
  // WHERE these bytes will live is decided by the ACTIVE backend selector —
  // LOCAL_PRIVATE under MEDIA_BACKEND=local, S3 under MEDIA_BACKEND=s3 — and
  // never inferred from the key or a filesystem path. Resolved BEFORE any byte
  // is written so an unsupported MEDIA_BACKEND fails closed with nothing
  // touched (no object, no row).
  const storage = activeMediaStorageValue();
  // Phase 21 — volume quota, checked BEFORE any byte is written or any DB row
  // is created. No-op unless the operator sets MEDIA_QUOTA_BYTES.
  const quota = await assertVolumeQuota(buffer.length);
  if (!quota.ok) {
    return {
      ok: false,
      code: "QUOTA_EXCEEDED",
      message: "Media storage quota exceeded",
    };
  }
  // Bytes go to that same active backend. mimeType/originalName ride along for
  // backends that can persist them (S3 ContentType); the MediaAsset row stays
  // the source of truth for both.
  await writePrivateFile(storageKey, buffer, {
    mimeType: validation.mimeType,
    originalName: validation.originalName,
  });

  const finalized = await finalizeLessonPdfMaterial(
    {
      lesson: { id: lesson.id, title: lesson.title },
      trackScope,
      title: typeof input.title === "string" ? input.title : null,
      storage,
      storageKey,
      mimeType: validation.mimeType,
      sizeBytes: validation.sizeBytes,
      originalName: validation.originalName,
      actorUserId: input.actorUserId,
    },
    client
  );
  if (!finalized.ok) {
    if (finalized.code === "ALREADY_LINKED") {
      // UNREACHABLE on the buffered path: no serialize gate is passed, so
      // the ALREADY_LINKED outcome can never be produced here. Refuse
      // loudly instead of widening MaterialUploadResult with the presigned
      // flow's concurrency concerns.
      throw new Error(
        "finalizeLessonPdfMaterial reported ALREADY_LINKED without a concurrency gate"
      );
    }
    return { ok: false, code: finalized.code, message: finalized.message };
  }
  return {
    ok: true,
    material: finalized.material,
    replaced: finalized.replaced,
    cleanedUpAssets: finalized.cleanedUpAssets,
  };
}

/**
 * Deactivate a material. Bytes are cleaned up only when no other row still
 * references the underlying MediaAsset.
 */
export async function deactivateMaterial(
  materialId: string,
  client: typeof db = db
): Promise<
  | { ok: true; cleanedUpAsset: string | null }
  | { ok: false; code: "MATERIAL_NOT_FOUND"; message: string }
> {
  const material = await client.material.findUnique({
    where: { id: materialId },
    select: { id: true, mediaAssetId: true, isActive: true },
  });
  if (!material) {
    return { ok: false, code: "MATERIAL_NOT_FOUND", message: "Material not found" };
  }

  if (material.isActive) {
    await client.material.update({
      where: { id: materialId },
      data: { isActive: false },
    });
  }

  let cleanedUpAsset: string | null = null;
  if (material.mediaAssetId) {
    const removed = await cleanupUnreferencedMediaAsset(
      material.mediaAssetId,
      client
    );
    if (removed) cleanedUpAsset = material.mediaAssetId;
  }
  return { ok: true, cleanedUpAsset };
}

/**
 * Delete a MediaAsset (and its private bytes) only when NOTHING still
 * references it: no Material, no SessionVideo, no QuizAttemptEvidence.
 * Returns true when the asset was removed.
 *
 * The bytes may live in EITHER managed private backend — LOCAL_PRIVATE (the
 * private volume) or S3 (Cloudflare R2) — and both are removed through the
 * same storage abstraction, addressed by the backend the row records.
 */
export async function cleanupUnreferencedMediaAsset(
  mediaAssetId: string,
  client: typeof db = db
): Promise<boolean> {
  const [materialRefs, videoRefs, evidenceRefs, asset] = await Promise.all([
    client.material.count({ where: { mediaAssetId } }),
    client.sessionVideo.count({ where: { mediaAssetId } }),
    client.quizAttemptEvidence.count({ where: { mediaAssetId } }),
    client.mediaAsset.findUnique({
      where: { id: mediaAssetId },
      select: { id: true, storage: true, storageKey: true },
    }),
  ]);

  if (!asset) return false;
  // Active OR inactive materials still count — a deactivated material that
  // keeps its mediaAssetId is a surviving reference (audit / restore path).
  // Callers that want cleanup after deactivate must null the FK first, OR we
  // count only when the material row still points at the asset. The contract
  // is: do not delete bytes while any Material row references them.
  if (materialRefs > 0 || videoRefs > 0 || evidenceRefs > 0) return false;

  // ORDER IS THE SAFETY PROPERTY: delete the OBJECT first, the row second.
  // If the object delete throws (an S3/R2 service error, a permissions
  // problem, a volume failure) this function rejects and the MediaAsset row
  // SURVIVES — the reference stays visible and the next cleanup run retries.
  // Deleting the row first would orphan the bytes with nothing left to point
  // at them.
  if (isManagedPrivateStorage(asset.storage) && asset.storageKey) {
    await deletePrivateFile(asset.storageKey, asset.storage);
  }
  await client.mediaAsset.delete({ where: { id: mediaAssetId } }).catch(() => {});
  return true;
}

/**
 * After deactivating a material, optionally release its MediaAsset reference
 * so cleanup can proceed. Used by admin hard-replace when the prior material
 * is not needed for history beyond the AuditLog.
 *
 * Default replace path KEEPS the deactivated Material → MediaAsset link so
 * historical rows remain restorable; cleanup then only fires when the admin
 * explicitly detaches or when no Material remains.
 *
 * For the Phase 14 "stale asset cleanup" path: when a material is deactivated
 * AND no other Material/Video/Evidence references the asset, we still keep the
 * deactivated row's FK (so `materialRefs > 0`). To actually free bytes on
 * replace, the upload path detaches prior materials' mediaAssetId after
 * deactivating them when the caller opts in — see `releaseDetachedAssets`.
 */
export async function releaseDetachedAssets(
  priorMediaAssetIds: (string | null)[],
  client: typeof db = db
): Promise<string[]> {
  const cleaned: string[] = [];
  for (const id of priorMediaAssetIds) {
    if (!id) continue;
    // Detach deactivated materials that still point at this asset so the
    // reference count can drop to zero. Only materials that are already
    // inactive are detached — never an active one.
    await client.material.updateMany({
      where: { mediaAssetId: id, isActive: false },
      data: { mediaAssetId: null },
    });
    const removed = await cleanupUnreferencedMediaAsset(id, client);
    if (removed) cleaned.push(id);
  }
  return cleaned;
}

