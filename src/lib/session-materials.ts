/**
 * Parse a trackScope supplied by an admin on upload.
 *   - absent / empty → null (caller inherits the lesson's scope)
 *   - SHARED/ARABIC/LANGUAGE → that scope
 *   - anything else → reject
 */
export function parseMaterialTrackScopeInput(
  raw: unknown
):
  | { ok: true; specified: false }
  | { ok: true; specified: true; value: TrackScope }
  | { ok: false } {
  if (raw === undefined || raw === null) return { ok: true, specified: false };
  if (typeof raw !== "string") return { ok: false };
  const v = raw.trim();
  if (v === "") return { ok: true, specified: false };
  const scope = normalizeTrackScope(v);
  if (!scope) return { ok: false };
  return { ok: true, specified: true, value: scope };
}

/**
 * Upload (or replace) the active PDF material for a lesson × trackScope.
 *
 * Side effects, in order, inside a transaction where possible:
 *   1. Validate bytes (MIME / extension / magic / size).
 *   2. Write private file under an unguessable key.
 *   3. Create MediaAsset(DOCUMENT, LOCAL_PRIVATE, isPrivate).
 *   4. Deactivate prior active Material rows of the same (lesson, trackScope).
 *   5. Create the new Material(ADMIN_UPLOADED) row.
 *   6. Reference-count cleanup of orphaned prior assets (after commit).
 *
 * NEVER writes `Lesson.pdfUrl`. NEVER trusts a client-supplied storageKey.
 */
export async function uploadLessonPdfMaterial(
  input: MaterialUploadInput,
  client: typeof db = db
): Promise<MaterialUploadResult> {
  const lesson = await client.lesson.findUnique({
    where: { id: input.lessonId },
    select: {
      id: true,
      title: true,
      titleAr: true,
      trackScope: true,
      curriculumStatus: true,
      status: true,
    },
  });
  if (!lesson) {
    return {
      ok: false,
      code: "LESSON_NOT_FOUND",
      message: "Lesson not found",
    };
  }
  if (String(lesson.curriculumStatus).toUpperCase() === "ARCHIVED") {
    return {
      ok: false,
      code: "LESSON_ARCHIVED",
      message: "Cannot attach materials to an archived lesson",
    };
  }

  const scopeParse = parseMaterialTrackScopeInput(input.trackScope);
  if (!scopeParse.ok) {
    return {
      ok: false,
      code: "INVALID_TRACK_SCOPE",
      message: "trackScope must be SHARED, ARABIC, or LANGUAGE",
    };
  }
  const trackScope: TrackScope = scopeParse.specified
    ? scopeParse.value
    : normalizeTrackScope(lesson.trackScope) ?? "SHARED";

  const validation = validatePdfUpload({
    buffer: input.buffer,
    claimedMime: input.claimedMime,
    originalName: input.originalName,
    maxBytes: input.maxBytes ?? MAX_PDF_BYTES,
  });
  if (!validation.ok) {
    return {
      ok: false,
      code: "VALIDATION_FAILED",
      message: validation.message,
      validation,
    };
  }

  const storageKey = makeStorageKey("session-pdfs", "pdf");
  const buffer = Buffer.isBuffer(input.buffer)
    ? input.buffer
    : Buffer.from(input.buffer);
  await writePrivateFile(storageKey, buffer);

  const title =
    (typeof input.title === "string" && input.title.trim()) ||
    validation.originalName ||
    `${lesson.title} PDF`;

  // Capture prior active materials so we can deactivate + maybe clean up.
  const prior = await client.material.findMany({
    where: {
      lessonId: lesson.id,
      trackScope,
      isActive: true,
      kind: "ADMIN_UPLOADED",
    },
    select: { id: true, mediaAssetId: true },
  });

  const apply = async (tx: any) => {
    if (prior.length > 0) {
      await tx.material.updateMany({
        where: { id: { in: prior.map((p) => p.id) } },
        data: { isActive: false },
      });
    }

    const asset = await tx.mediaAsset.create({
      data: {
        kind: "DOCUMENT",
        storage: "LOCAL_PRIVATE",
        storageKey,
        mimeType: validation.mimeType,
        sizeBytes: validation.sizeBytes,
        originalName: validation.originalName,
        isPrivate: true,
        createdById: input.actorUserId ?? null,
      },
    });

    const material = await tx.material.create({
      data: {
        lessonId: lesson.id,
        kind: "ADMIN_UPLOADED",
        title: title.slice(0, 200),
        mediaAssetId: asset.id,
        // storageKey on Material is legacy; the asset owns the key. Leave null
        // so nothing ever confuses the two.
        storageKey: null,
        trackScope,
        isActive: true,
      },
    });

    return { asset, material };
  };

  let created: Awaited<ReturnType<typeof apply>>;
  if (typeof (client as { $transaction?: unknown }).$transaction === "function") {
    created = await (client as typeof db).$transaction(apply);
  } else {
    created = await apply(client);
  }

  // Reference-counted cleanup: detach deactivated materials from their prior
  // assets, then delete any asset that nothing else still references. An asset
  // still pointed at by another active Material (or a SessionVideo / evidence
  // row) is retained — never delete shared bytes.
  const cleanedUpAssets = await releaseDetachedAssets(
    prior
      .map((p) => p.mediaAssetId)
      .filter((id): id is string => !!id && id !== created.asset.id),
    client
  );

  return {
    ok: true,
    material: {
      id: created.material.id,
      lessonId: lesson.id,
      title: created.material.title,
      kind: "ADMIN_UPLOADED",
      trackScope,
      isActive: true,
      mediaAssetId: created.asset.id,
      downloadUrl: `/api/materials/${created.material.id}`,
      mimeType: validation.mimeType,
      sizeBytes: validation.sizeBytes,
      originalName: validation.originalName,
    },
    replaced: prior.map((p) => ({
      materialId: p.id,
      mediaAssetId: p.mediaAssetId,
    })),
    cleanedUpAssets,
  };
}

/**
 * Deactivate a material. Bytes are cleaned up only when no other row still
 * references the underlying MediaAsset.
 */
export async function deactivateMaterial(
  materialId: string,
  client: typeof db = db
): Promise<
  | { ok: true; cleanedUpAsset: string | null }
  | { ok: false; code: "MATERIAL_NOT_FOUND"; message: string }
> {
  const material = await client.material.findUnique({
    where: { id: materialId },
    select: { id: true, mediaAssetId: true, isActive: true },
  });
  if (!material) {
    return { ok: false, code: "MATERIAL_NOT_FOUND", message: "Material not found" };
  }

  if (material.isActive) {
    await client.material.update({
      where: { id: materialId },
      data: { isActive: false },
    });
  }

  let cleanedUpAsset: string | null = null;
  if (material.mediaAssetId) {
    const removed = await cleanupUnreferencedMediaAsset(
      material.mediaAssetId,
      client
    );
    if (removed) cleanedUpAsset = material.mediaAssetId;
  }
  return { ok: true, cleanedUpAsset };
}

/**
 * Delete a MediaAsset (and its private bytes) only when NOTHING still
 * references it: no Material, no SessionVideo, no QuizAttemptEvidence.
 * Returns true when the asset was removed.
 */
export async function cleanupUnreferencedMediaAsset(
  mediaAssetId: string,
  client: typeof db = db
): Promise<boolean> {
  const [materialRefs, videoRefs, evidenceRefs, asset] = await Promise.all([
    client.material.count({ where: { mediaAssetId } }),
    client.sessionVideo.count({ where: { mediaAssetId } }),
    client.quizAttemptEvidence.count({ where: { mediaAssetId } }),
    client.mediaAsset.findUnique({
      where: { id: mediaAssetId },
      select: { id: true, storage: true, storageKey: true },
    }),
  ]);

  if (!asset) return false;
  // Active OR inactive materials still count — a deactivated material that
  // keeps its mediaAssetId is a surviving reference (audit / restore path).
  // Callers that want cleanup after deactivate must null the FK first, OR we
  // count only when the material row still points at the asset. The contract
  // is: do not delete bytes while any Material row references them.
  if (materialRefs > 0 || videoRefs > 0 || evidenceRefs > 0) return false;

  if (asset.storage === "LOCAL_PRIVATE" && asset.storageKey) {
    await deletePrivateFile(asset.storageKey);
  }
  await client.mediaAsset.delete({ where: { id: mediaAssetId } }).catch(() => {});
  return true;
}

/**
 * After deactivating a material, optionally release its MediaAsset reference
 * so cleanup can proceed. Used by admin hard-replace when the prior material
 * is not needed for history beyond the AuditLog.
 *
 * Default replace path KEEPS the deactivated Material → MediaAsset link so
 * historical rows remain restorable; cleanup then only fires when the admin
 * explicitly detaches or when no Material remains.
 *
 * For the Phase 14 "stale asset cleanup" path: when a material is deactivated
 * AND no other Material/Video/Evidence references the asset, we still keep the
 * deactivated row's FK (so `materialRefs > 0`). To actually free bytes on
 * replace, the upload path detaches prior materials' mediaAssetId after
 * deactivating them when the caller opts in — see `releaseDetachedAssets`.
 */
export async function releaseDetachedAssets(
  priorMediaAssetIds: (string | null)[],
  client: typeof db = db
): Promise<string[]> {
  const cleaned: string[] = [];
  for (const id of priorMediaAssetIds) {
    if (!id) continue;
    // Detach deactivated materials that still point at this asset so the
    // reference count can drop to zero. Only materials that are already
    // inactive are detached — never an active one.
    await client.material.updateMany({
      where: { mediaAssetId: id, isActive: false },
      data: { mediaAssetId: null },
    });
    const removed = await cleanupUnreferencedMediaAsset(id, client);
    if (removed) cleaned.push(id);
  }
  return cleaned;
}

