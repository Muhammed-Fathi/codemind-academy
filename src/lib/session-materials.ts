/** Safe descriptor returned to students/parents/admins. No storage keys. */
export type MaterialDescriptor = {
  id: string;
  title: string;
  kind: "ADMIN_UPLOADED" | "GENERATED" | "LEGACY_URL";
  trackScope: TrackScope;
  /** Authorized download path — NEVER a filesystem path or private URL. */
  downloadUrl: string | null;
  mimeType: string | null;
  sizeBytes: number | null;
  /** true when this is a legacy `Lesson.pdfUrl` compatibility descriptor. */
  legacy: boolean;
};

export type MaterialUploadInput = {
  lessonId: string;
  buffer: Buffer | Uint8Array;
  claimedMime?: string | null;
  originalName?: string | null;
  title?: string | null;
  /** Defaults to the lesson's own trackScope when omitted. */
  trackScope?: unknown;
  actorUserId?: string | null;
  maxBytes?: number;
};

export type MaterialUploadResult =
  | {
      ok: true;
      material: {
        id: string;
        lessonId: string;
        title: string;
        kind: "ADMIN_UPLOADED";
        trackScope: TrackScope;
        isActive: true;
        mediaAssetId: string;
        downloadUrl: string;
        mimeType: string;
        sizeBytes: number;
        originalName: string;
      };
      replaced: { materialId: string; mediaAssetId: string | null }[];
      cleanedUpAssets: string[];
    }
  | {
      ok: false;
      code:
        | "LESSON_NOT_FOUND"
        | "LESSON_ARCHIVED"
        | "VALIDATION_FAILED"
        | "INVALID_TRACK_SCOPE";
      message: string;
      validation?: PdfValidationResult;
    };

export type MaterialAccessReason =
  | AccessReason
  | "MATERIAL_NOT_FOUND"
  | "MATERIAL_INACTIVE"
  | "ASSET_NOT_FOUND"
  | "TRACK_DENIED"
  | "FORBIDDEN_ROLE"
  | "UNAUTHORIZED";

export type MaterialAccess =
  | {
      allowed: true;
      reason: null;
      material: {
        id: string;
        lessonId: string;
        title: string;
        trackScope: TrackScope;
        isActive: boolean;
        mediaAssetId: string;
      };
      asset: {
        id: string;
        storageKey: string;
        mimeType: string | null;
        sizeBytes: number | null;
        originalName: string | null;
        isPrivate: boolean;
        storage: string;
        kind: string;
      };
      lesson: {
        id: string;
        status: string;
        trackScope: TrackScope;
        curriculumStatus: string;
        courseId: string | null;
      };
    }
  | { allowed: false; reason: MaterialAccessReason };

